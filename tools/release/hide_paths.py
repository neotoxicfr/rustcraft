"""Keep the paths of the build machine out of the executable.

    python -I tools/release/hide_paths.py config <out.toml>   # then: cargo build --config <out.toml> ...
    python -I tools/release/hide_paths.py check <binary>      # exit 1 if a machine path is still inside

Why a generated file: the dependencies' sources live under the cargo home (`~/.cargo/registry/src/...`)
and rustc writes their absolute path into every panic message. Cargo's `trim-paths` profile option
would hide them but is not stable in the pinned toolchain, and `--remap-path-prefix` needs the
absolute path, which is different on every machine (and contains the user name), so it cannot be
committed in `.cargo/config.toml`. The file holds only the remap flags: the committed config still
supplies the linker flags, and cargo joins both lists.

The checkout itself needs no rule for panic messages (workspace files are given to rustc as relative
paths), but it is remapped too so that the debug info of a local build does not name it either.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Machine path -> the fixed name it gets in the binary.
CARGO_HOME_AS = "/cargo"
CHECKOUT_AS = "/src"


def cargo_home(environ=os.environ):
    return environ.get("CARGO_HOME") or os.path.join(os.path.expanduser("~"), ".cargo")


def remap_flags(cargo_home_dir, checkout_dir):
    return [
        f"--remap-path-prefix={cargo_home_dir}={CARGO_HOME_AS}",
        f"--remap-path-prefix={checkout_dir}={CHECKOUT_AS}",
    ]


def config_text(flags):
    """A cargo config file with the flags for every target. Literal TOML strings: no escaping of `\\`."""
    for flag in flags:
        if "'" in flag or "\n" in flag:
            raise SystemExit(f"cannot write this path into a config file: {flag!r}")
    items = "".join(f"    '{flag}',\n" for flag in flags)
    return (
        "# Generated by tools/release/hide_paths.py for this machine; not committed.\n"
        "[target.'cfg(all())']\n"
        f"rustflags = [\n{items}]\n"
    )


def machine_paths(environ=os.environ):
    """What must not appear in a binary: the cargo home, the checkout and the home directory (user name)."""
    paths = [cargo_home(environ), ROOT, os.path.expanduser("~")]
    return [os.path.normpath(p) for p in paths if p]


def spellings(path):
    """The path as written with each kind of separator (rustc keeps the one the system gave it)."""
    return {path, path.replace("\\", "/"), path.replace("/", "\\")}


def find_leaks(data, paths):
    """{path: number of occurrences in `data`} for every path found at least once."""
    found = {}
    for path in paths:
        count = sum(data.count(s.encode()) for s in spellings(path))
        if count:
            found[path] = count
    return found


def main(argv):
    if len(argv) == 3 and argv[1] == "config":
        with open(argv[2], "w", newline="\n") as f:
            f.write(config_text(remap_flags(os.path.normpath(cargo_home()), ROOT)))
    elif len(argv) == 3 and argv[1] == "check":
        with open(argv[2], "rb") as f:
            leaks = find_leaks(f.read(), machine_paths())
        for path, count in leaks.items():
            print(f"{argv[2]}: {count} x {path}")
        if leaks:
            raise SystemExit(1)
        print(f"{argv[2]}: no machine path")
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
