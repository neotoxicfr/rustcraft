//! Bit-for-bit equivalence of the optimised terrain paths (`TerrainOpts`, switches
//! `RUSTCRAFT_OPT_TERRAIN_IDS`, `AQ_COLWIN`, `AQ_SIMD`, `AQ_PRETEST`, `BASEH_LAZY`, `BASEH_MEMO`,
//! `CARVER_YD`, `CARVER_WIDTHS`, `CARVER_REPLAY`) against the old code: complete chunks
//! (blocks, height maps, fluid marks), aquifer block by block with drawn densities,
//! base heights, cave masks. Missing game data makes the tests fail under
//! `RUSTCRAFT_OPT_REQUIRE=1`.

mod common;

use rayon::prelude::*;
use rc_worldgen::Ctx;
use rc_worldgen::proto::ProtoTerrain;
use rc_worldgen::terrain::{BiomeCache, TerrainGenerator, TerrainOpts};

/// splitmix64 for the test draws.
struct Mix(u64);

impl Mix {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
    fn range(&mut self, lo: i32, hi: i32) -> i32 {
        lo + (self.next() % (hi - lo) as u64) as i32
    }
    fn unit(&mut self) -> f64 {
        (self.next() >> 11) as f64 / (1u64 << 53) as f64
    }
}

const SEEDS: [i64; 3] = [0, -6_214_586_474_519_478_921, 1_234_567_890_123_456_789];
const DIMS: [(&str, &str); 4] = [
    ("minecraft:normal", "minecraft:overworld"),
    ("minecraft:amplified", "minecraft:overworld"),
    ("minecraft:normal", "minecraft:the_nether"),
    ("minecraft:normal", "minecraft:the_end"),
];

/// Each switch alone, then all.
fn variants() -> Vec<(&'static str, TerrainOpts)> {
    let o = TerrainOpts::OLD;
    vec![
        ("ids", TerrainOpts { ids: true, ..o }),
        ("aq_colwin", TerrainOpts { aq_colwin: true, ..o }),
        ("aq_colwin+net", TerrainOpts { aq_colwin: true, aq_net: true, ..o }),
        ("aq_pretest", TerrainOpts { aq_pretest: true, ..o }),
        ("carver_yd", TerrainOpts { carver_yd: true, ..o }),
        ("carver_widths", TerrainOpts { carver_widths: true, ..o }),
        ("carver_replay", TerrainOpts { carver_replay: true, ..o }),
        ("all", TerrainOpts::NEW),
    ]
}

fn generator(
    pack: &rc_worldgen::data::DataPack,
    preset: &str,
    dim: &str,
    seed: i64,
    o: TerrainOpts,
) -> TerrainGenerator {
    let mut t = TerrainGenerator::from_preset(pack, preset, dim, seed).expect("generator");
    t.opts = o;
    t
}

/// Difference between two chunks, `None` if identical.
fn diff(a: &ProtoTerrain, b: &ProtoTerrain) -> Option<String> {
    if let Some(i) = a.blocks.iter().zip(&b.blocks).position(|(x, y)| x != y) {
        return Some(format!("block {i}: {} ≠ {}", a.blocks[i], b.blocks[i]));
    }
    if !a.world_surface_wg.iter().eq(b.world_surface_wg.iter()) {
        return Some("surface map".into());
    }
    if !a.ocean_floor_wg.iter().eq(b.ocean_floor_wg.iter()) {
        return Some("floor map".into());
    }
    if a.post_processing != b.post_processing {
        return Some(format!("marks ({} against {})", a.post_processing.len(), b.post_processing.len()));
    }
    None
}

/// Chunks drawn at random (and a few fixed ones), generated by the old path then by each
/// variant: result identical to the block.
fn check_chunks(pack: &rc_worldgen::data::DataPack, sabotage: bool) -> Vec<String> {
    let mut failures = Vec::new();
    for (preset, dim) in DIMS {
        for seed in SEEDS {
            let mut rng = Mix(seed as u64 ^ dim.len() as u64 ^ preset.len() as u64);
            let mut targets = vec![(0, 0), (-1, -1), (5, -7), (12, 3)];
            targets.extend((0..6).map(|_| (rng.range(-3000, 3000), rng.range(-3000, 3000))));
            let old = generator(pack, preset, dim, seed, TerrainOpts::OLD);
            let mut cache = BiomeCache::default();
            old.prepare_biomes(&mut cache, &targets);
            let reference: Vec<ProtoTerrain> =
                targets.par_iter().map(|&(x, z)| old.generate(x, z, &cache, None)).collect();
            for (name, o) in variants() {
                let t = generator(pack, preset, dim, seed, o);
                let got: Vec<ProtoTerrain> = targets.par_iter().map(|&(x, z)| t.generate(x, z, &cache, None)).collect();
                for (i, (a, b)) in reference.iter().zip(&got).enumerate() {
                    let mut b = b.clone();
                    if sabotage && i == 0 {
                        // Sabotage: a lost fluid mark must be seen.
                        b.post_processing.pop();
                        if b.post_processing.len() == a.post_processing.len() {
                            b.blocks[0] ^= 1;
                        }
                    }
                    if let Some(d) = diff(a, &b) {
                        failures.push(format!("{dim} {preset} seed {seed} {:?} [{name}]: {d}", targets[i]));
                    }
                }
            }
        }
    }
    failures
}

#[test]
fn terrain_paths_identical() {
    let Some(pack) = common::data_pack() else { return };
    let failures = check_chunks(&pack, false);
    assert!(failures.is_empty(), "{} differences:\n{}", failures.len(), failures.join("\n"));
}

#[test]
fn terrain_check_catches_sabotage() {
    let Some(pack) = common::data_pack() else { return };
    let failures = check_chunks(&pack, true);
    assert!(!failures.is_empty(), "the sabotage was not seen");
}

/// Aquifer block by block: generic path, column window (insertion) and window + network,
/// on densities drawn in [−0.6; 0.4] (barriers, pressures, distance ties).
fn check_aquifer(pack: &rc_worldgen::data::DataPack, sabotage: bool) -> (usize, Vec<String>) {
    let mut failures = Vec::new();
    let mut fluid = 0usize;
    for (preset, dim) in DIMS {
        for seed in SEEDS {
            let t = generator(pack, preset, dim, seed, TerrainOpts::OLD);
            let mut rng = Mix(seed as u64 ^ 0x5EED ^ dim.len() as u64);
            for n in 0..4 {
                let (cx, cz) = if n == 0 { (0, 0) } else { (rng.range(-2000, 2000), rng.range(-2000, 2000)) };
                let Some(vol) = t.fill_volume(cx, cz) else { continue };
                let (mut c0, mut c1, mut c2) = (Ctx::cached(), Ctx::cached(), Ctx::cached());
                let mut a = t.new_aquifer(&mut c0, &vol);
                let mut b = t.new_aquifer(&mut c1, &vol);
                let mut c = t.new_aquifer(&mut c2, &vol);
                for z in 0..vol.sz {
                    for x in 0..vol.sx {
                        let (bx, bz) = (vol.bx(x), vol.bz(z));
                        for y in (0..vol.sy).rev() {
                            let by = vol.by(y);
                            let d = rng.unit() - 0.6;
                            let ra = a.compute(&t.g, &mut c0, bx, by, bz, d);
                            let rb = b.compute_column(&t.g, &mut c1, bx, by, bz, d, false);
                            let mut rc = c.compute_column(&t.g, &mut c2, bx, by, bz, d, true);
                            if sabotage && ra.0.is_some() && ra.1 {
                                rc.1 = !rc.1;
                            }
                            if ra.0.is_some_and(|s| s != 0) {
                                fluid += 1;
                            }
                            if ra != rb || ra != rc {
                                failures.push(format!(
                                    "{dim} seed {seed} ({bx}, {by}, {bz}) d {d}: {ra:?} / {rb:?} / {rc:?}"
                                ));
                            }
                        }
                    }
                }
            }
        }
    }
    (fluid, failures)
}

#[test]
fn aquifer_paths_identical() {
    let Some(pack) = common::data_pack() else { return };
    let (fluid, failures) = check_aquifer(&pack, false);
    assert!(fluid > 10_000, "too little fluid drawn ({fluid})");
    assert!(failures.is_empty(), "{} differences:\n{}", failures.len(), failures[..failures.len().min(20)].join("\n"));
}

#[test]
fn aquifer_check_catches_sabotage() {
    let Some(pack) = common::data_pack() else { return };
    let (_, failures) = check_aquifer(&pack, true);
    assert!(!failures.is_empty(), "the sabotage was not seen");
}

/// Base heights: 5,000 columns × 2 types × 3 dimensions, old path against lazy
/// slices (fixed splits, doubled, probe, adaptive probe) and memo (second pass
/// served by the memo); slice density compared bit for bit with the whole volume.
#[test]
fn base_height_paths_identical() {
    let Some(pack) = common::data_pack() else { return };
    let mut failures = Vec::new();
    for (preset, dim) in [DIMS[0], DIMS[2], DIMS[3]] {
        let seed = 0;
        let old = generator(&pack, preset, dim, seed, TerrainOpts::OLD);
        let lazy = TerrainOpts { baseh_lazy: true, ..TerrainOpts::OLD };
        let mut news: Vec<TerrainGenerator> = [(0, 1), (0, 4), (1, 1), (1, 2), (2, 1), (2, 4), (3, 1)]
            .iter()
            .map(|&(mode, cells)| {
                let mut t = generator(&pack, preset, dim, seed, lazy);
                t.lazy_mode = mode;
                t.lazy_cells = cells;
                t
            })
            .collect();
        news.push(generator(&pack, preset, dim, seed, TerrainOpts::NEW));
        news.push(generator(&pack, preset, dim, seed, TerrainOpts { baseh_memo: true, ..TerrainOpts::OLD }));
        let mut rng = Mix(0xBA5E ^ dim.len() as u64);
        // Both types on each column (memo key), 10,000 calls.
        let cols: Vec<(i32, i32, bool)> = (0..5_000)
            .flat_map(|_| {
                let (x, z) = (rng.range(-30_000, 30_000), rng.range(-30_000, 30_000));
                [(x, z, false), (x, z, true)]
            })
            .collect();
        // Slice density identical bit for bit to the whole volume, for each split.
        for t in news.iter().take(7) {
            for &(x, z, _) in cols.iter().step_by(40) {
                let (lazy, full) = t.lazy_density_check(x, z);
                let same = lazy.len() == full.len() && lazy.iter().zip(&full).all(|(a, b)| a.to_bits() == b.to_bits());
                if !same {
                    failures.push(format!(
                        "{dim} mode {} cells {} ({x}, {z}): slice density differs",
                        t.lazy_mode, t.lazy_cells
                    ));
                }
            }
        }
        let reference: Vec<i32> = cols.par_iter().map(|&(x, z, f)| old.base_height(x, z, f)).collect();
        for (k, t) in news.iter().enumerate() {
            for pass in 0..2 {
                let got: Vec<i32> = cols.par_iter().map(|&(x, z, f)| t.base_height(x, z, f)).collect();
                for (i, (a, b)) in reference.iter().zip(&got).enumerate() {
                    if a != b {
                        failures.push(format!("{dim} variant {k} pass {pass} {:?}: {a} ≠ {b}", cols[i]));
                    }
                }
            }
        }
        let (calls, hits) = news.last().expect("memo").base_height_stats();
        if (calls, hits) != (20_000, 10_000) {
            failures.push(format!("{dim} memo: {calls} calls, {hits} served (expected 20,000, 10,000)"));
        }
        let differ = cols.chunks(2).zip(reference.chunks(2)).filter(|(_, h)| h[0] != h[1]).count();
        // Surface and floor differ only where there is water (main world).
        assert!(!dim.ends_with("overworld") || differ > 100, "{dim}: surface and floor too rarely distinct ({differ})");
        let distinct: std::collections::HashSet<i32> = reference.iter().copied().collect();
        // Nether: bedrock ceiling, always 128 (first block read); it only tests the stop.
        assert!(dim.ends_with("nether") || distinct.len() > 5, "{dim}: heights too uniform {distinct:?}");
    }
    // Whole columns (structures): unchanged by the slices.
    let t = generator(&pack, DIMS[0].0, DIMS[0].1, 0, TerrainOpts::NEW);
    let o = generator(&pack, DIMS[0].0, DIMS[0].1, 0, TerrainOpts::OLD);
    assert_eq!(t.base_column(123, -456), o.base_column(123, -456));
    assert!(failures.is_empty(), "{} differences:\n{}", failures.len(), failures[..failures.len().min(20)].join("\n"));
}

/// Cave masks: 500 targets, direct carving against replay (and precomputed vertical difference,
/// width buffer); the replay then serves from the cache, second pass included.
#[test]
fn carving_masks_identical() {
    let Some(pack) = common::data_pack() else { return };
    let mut failures = Vec::new();
    for (preset, dim) in [DIMS[0], DIMS[2]] {
        for seed in SEEDS {
            let old = generator(&pack, preset, dim, seed, TerrainOpts::OLD);
            let new = generator(&pack, preset, dim, seed, TerrainOpts::NEW);
            let mut rng = Mix(seed as u64 ^ 0xCA7E);
            // Grouped targets (shared sources) and sparse ones.
            let mut targets: Vec<(i32, i32)> = (0..12).flat_map(|x| (0..12).map(move |z| (x, z))).collect();
            targets.extend((0..356).map(|_| (rng.range(-5000, 5000), rng.range(-5000, 5000))));
            let mut cache = BiomeCache::default();
            old.prepare_biomes(&mut cache, &targets);
            let a: Vec<_> = targets.par_iter().map(|&(x, z)| old.carving_mask(x, z, &cache)).collect();
            let mut carved = 0;
            for pass in 0..2 {
                let b: Vec<_> = targets.par_iter().map(|&(x, z)| new.carving_mask(x, z, &cache)).collect();
                for (i, (ma, mb)) in a.iter().zip(&b).enumerate() {
                    carved += usize::from(!ma.is_empty());
                    if ma != mb {
                        failures.push(format!("{dim} seed {seed} pass {pass} {:?}", targets[i]));
                    }
                }
            }
            assert!(carved > 100, "{dim}: too few carved chunks ({carved})");
        }
    }
    assert!(failures.is_empty(), "{} differences:\n{}", failures.len(), failures[..failures.len().min(20)].join("\n"));
}
